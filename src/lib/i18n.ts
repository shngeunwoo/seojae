const dictionaries: Record<Lang, Record<DictKey, string>> = { ko, en }

export function translate(
  lang: Lang,
  key: DictKey,
  vars?: Record<string, string | number>,
) {
  let text = dictionaries[lang][key] ?? dictionaries.ko[key]
  if (!vars) return text
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function greetingKey(hour: number): DictKey {
  if (hour < 5 || hour >= 22) return "greetNight"
  if (hour < 12) return "greetMorning"
  if (hour < 18) return "greetAfternoon"
  return "greetEvening"
}
